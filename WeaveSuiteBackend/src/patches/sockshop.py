"""
SockShop OpenAPI patch registry.

Each entry aligns the specification generated by Helidon's MicroProfile OpenAPI (from
the JAX-RS resources and their annotations) with the behaviour of the deployed service,
verified against its source. The source is read white-box, but the LLM
that generates the tests sees only the patched specification (black-box generation).
Every entry is tagged with at least one criterion of the ones detailed below:

  Precision of the documented response surface
    (a) response accuracy              (c) absence of unreachable responses
    (b) response completeness          (d) error-condition accuracy
  Completeness of the implicit operational constraints
    (e) operational semantics and preconditions
    (f) counter-intuitive success semantics

Comment layout per entry:
  # (x) criterion. Drift between the generated contract and the implementation.
  # PATCH: the edit applied to the specification.
  # CODE: where the behaviour lives in the implementation.

Patches are limited to these criteria: they document verified service behaviour, not
testing hints. Verified behaviour outside them was not added, for example:
  - the shipping carrier/trackingNumber branching on itemCount (internal rule, not
    part of the response surface or of the caller's preconditions);
  - redirects from /addresses and /cards to /customers/{id}/addresses and
    /customers/{id}/cards: the real listing endpoints are documented on their own.
"""
from typing import Any, Dict


